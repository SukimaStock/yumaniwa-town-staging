'use strict';
// Research is presentation metadata, never lifecycle or adoption authority.
const fs = require('node:fs');
const path = require('node:path');
const FILE = 'data/ambertime-research.json';
const OUTPUT = 'lab/ambertime-research.html';
const THEMES = ['蒸留とカット', '味と熟成', '販売と取扱店', '評判と地域拡大', '地図と視覚表現', '操作・画面設計'];
const LABELS = { active: '現役・再比較用', review: '要確認・通常表示を維持', record: '研究記録' };
function readResearch(root, works, raw = JSON.parse(fs.readFileSync(path.join(root, FILE), 'utf8'))) {
  if (raw.schema !== 'ambertime-research/1' || !Array.isArray(raw.records)) throw new Error('Research: invalid schema');
  const ids = new Set(), sources = new Set(), assigned = new Set();
  const local = file => typeof file === 'string' && /^works\/[a-z0-9-]+\/[a-zA-Z0-9_./-]+$/.test(file) && !file.split('/').includes('..') && fs.existsSync(path.join(root, file)) && fs.statSync(path.join(root, file)).isFile();
  const text = value => typeof value === 'string' && !!value.trim();
  const records = raw.records.map(record => {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(record.id) || ids.has(record.id) || sources.has(record.source) || !local(record.source) || !/\.html$/.test(record.source)) throw new Error('Research: invalid or duplicate source/id');
    if (!THEMES.includes(record.theme) || !LABELS[record.display] || typeof record.protection !== 'boolean' || !['version','purpose','findings','adoption','deferred'].every(key => text(record[key]))) throw new Error('Research: incomplete record ' + record.id);
    if (!Array.isArray(record.dependencies) || !record.dependencies.every(local) || !Array.isArray(record.references) || !record.references.length || !record.references.every(ref => local(ref) || /^https:\/\/github\.com\/SukimaStock\/yumaniwa-town-staging\/pull\/\d+$/.test(ref))) throw new Error('Research: invalid evidence ' + record.id);
    // No copied lifecycle state/path, or arbitrary launch URL.
    if (['status','href','path'].some(key => key in record)) throw new Error('Research: identity belongs to lifecycle');
    let work;
    if (record.work) {
      work = works.find(item => item.id === record.work);
      if (!work || !work.id.startsWith('ambertime-') || assigned.has(work.id) || !local(work.path + '/index.html')) throw new Error('Research: invalid registered work ' + record.work);
      assigned.add(work.id);
    } else if (!text(record.title)) throw new Error('Research: missing internal version title');
    ids.add(record.id); sources.add(record.source);
    return { ...record, title: work?.title || record.title, href: work ? work.path + '/' : record.source };
  });
  return { ...raw, records };
}
function renderResearch(root, research, esc) {
  const version = require('node:crypto').createHash('sha256').update(fs.readFileSync(path.join(root, 'lab/ambertime-research.css'))).digest('hex').slice(0,12);
  const link = (href, label) => `<a href="${href.startsWith('https:') ? esc(href) : '../' + esc(href)}">${esc(label)}</a>`;
  const themes = THEMES.filter(theme => research.records.some(record => record.theme === theme));
  return `<!doctype html>
<!-- Generated by tools/work-lifecycle.cjs --write-lab from ${FILE}. -->
<html lang="ja"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="robots" content="noindex"><title>AmberTime 研究記録 · SukimaStock LAB</title><link rel="stylesheet" href="./ambertime-research.css?v=${version}"></head>
<body><header><a href="./#room-bench">← LAB一覧へ</a></header><main id="main"><h1>AmberTime 研究記録</h1>
<p>現役の比較と、これまでの試作・検証をテーマごとにまとめています。採用状況が未確認のものも残しています。</p>
<nav aria-label="研究テーマ">${themes.map((theme, i) => `<a href="#theme-${i}">${esc(theme)}</a>`).join('\n')}</nav>
${themes.map((theme, i) => `<section aria-labelledby="theme-${i}"><h2 id="theme-${i}" tabindex="-1">${esc(theme)}</h2>${research.records.filter(record => record.theme === theme).map(record => `<details id="${record.id}"><summary>${esc(record.title)} <span>${esc(record.version)}</span></summary>
<p class="state">${LABELS[record.display]}${record.protection ? ' · 依存参照を保護' : ''}</p><dl><dt>試したこと</dt><dd>${esc(record.purpose)}</dd><dt>分かったこと</dt><dd>${esc(record.findings)}</dd><dt>本編への採用</dt><dd>${esc(record.adoption)}</dd><dt>見送り・保留</dt><dd>${esc(record.deferred)}</dd></dl>
<p>${link(record.href, '元のLabを開く')}${record.href !== record.source ? ' · ' + link(record.source, '実験の直接入口') : ''}</p>
<p class="references">根拠：${record.references.map((ref, index) => link(ref, ref.startsWith('https:') ? 'PR #' + ref.split('/').pop() : '資料' + (index + 1))).join(' · ')}</p>
</details>`).join('\n')}</section>`).join('\n')}
<p><a href="./#room-bench">← LAB一覧へ</a></p></main></body></html>\n`;
}
module.exports = { FILE, OUTPUT, THEMES, LABELS, readResearch, renderResearch };
